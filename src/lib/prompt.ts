export function buildUserPrompt(
  req: GenerateBlogRequest,
  samples: ReferenceSample[]
): string {
  const parts: string[] = [];

  parts.push("## 작성 요청");
  parts.push(`- 청소 종류: ${req.cleaningType}`);
  parts.push(`- 지역/아파트/현장: ${req.location}`);
  parts.push(`- 특이사항/시공 포인트: ${req.notes || "(없음 — 해당 청소 종류의 일반적인 작업 범위 안에서 서술)"}`);

  const guide = TYPE_GUIDES[req.cleaningType];
  if (guide) {
    parts.push(`\n## ${req.cleaningType} 전용 작성 가이드 (시스템 지침과 함께 반드시 반영)`);
    parts.push(guide);
  }

  parts.push("\n## 키워드 모드");
  if (req.keywordMode === "manual") {
    parts.push("모드: 직접 지정 (manual)");
    parts.push(`지정 키워드: ${req.keywords.map((k) => `"${k}"`).join(", ")}`);
    parts.push("→ 위 키워드 각각을 본문에 3~5회 자연스럽게 분산 배치하세요. autoKeywords 는 빈 배열로 두세요.");
  } else {
    parts.push("모드: 자동 (auto)");
    parts.push("→ 지역명과 청소 종류 기반으로 롱테일 키워드 3~4개를 직접 선정해 자연스럽게 녹이고 autoKeywords 에 담으세요.");
  }

  parts.push("\n## 업로드 이미지 (본문에 순서대로 모두 배치)");
  if (req.images.length === 0) {
    parts.push("이미지 없음 — 플레이스홀더를 만들지 마세요.");
  } else {
    parts.push(`총 ${req.images.length}장`);
    for (const img of req.images) {
      const desc = [img.tag, img.memo].filter(Boolean).join(" / ") || "(설명 없음 — 문맥상 적절한 위치에 배치)";
      parts.push(`- 사진 ${img.index}: ${desc}`);
    }
  }

  parts.push("\n## 말투 분석용 레퍼런스 글");
  if (samples.length === 0) {
    parts.push("(불러온 예시 글 없음 — 기본 톤앤매너를 사용하세요)");
  } else {
    samples.forEach((s, i) => {
      parts.push(`<reference index="${i + 1}" title="${s.title.replace(/"/g, "'")}">\n${s.text}\n</reference>`);
    });
  }

  parts.push("\n위 정보를 바탕으로 시스템 지침의 JSON 형식으로만 응답하세요.");
  return parts.join("\n");
}
